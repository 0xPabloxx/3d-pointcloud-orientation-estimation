#!/bin/bash
# =============================================================================
# Loss Ablation Experiments - 快速可行性验证
# =============================================================================
#
# 实验目的: 比较不同loss配置的效果
# 训练轮数: 15 epochs (快速验证)
# 记录方式: wandb + 本地checkpoint
#
# 实验顺序设计原则:
#   1. 先验证最简单case (纯4_fronts)
#   2. 再测试预期最稳定的配置 (纯监督)
#   3. 然后对比不同KL配置
#   4. 最后尝试高级策略
#
# 修改记录:
#   2025-12-11: 初始版本，GT已更新为κ=10，所有峰都有效
#   2025-12-11: 添加Reverse KL、两阶段训练、Loss调度实验
# =============================================================================

set -e  # 遇到错误立即退出

# 公共参数
EPOCHS=30
BATCH_SIZE=32
LR=0.001
NUM_WORKERS=4
WANDB_PROJECT="ForwardNet-LossAblation"

# 基础命令
BASE_CMD="python train_fixed_4peak.py \
    --epochs $EPOCHS \
    --batch_size $BATCH_SIZE \
    --lr $LR \
    --num_workers $NUM_WORKERS \
    --wandb \
    --wandb_project $WANDB_PROJECT"

echo "=============================================="
echo "Loss Ablation Experiments (9 experiments)"
echo "Epochs: $EPOCHS, Batch: $BATCH_SIZE, LR: $LR"
echo "=============================================="

# =============================================================================
# 第一组: 基础验证
# =============================================================================

# -----------------------------------------------------------------------------
# Exp-1: 纯4_fronts数据 (最简单case)
# -----------------------------------------------------------------------------
echo ""
echo "[Exp-1] 纯4_fronts数据验证 (λ_κ=5.0, λ_μ=2.0, 只用4_fronts)"
echo "----------------------------------------------"
$BASE_CMD \
    --lambda_kl 0.0 \
    --lambda_kappa 5.0 \
    --lambda_mu 2.0 \
    --categories 4_fronts \
    --exp_name "Exp1_4fronts_only"

# -----------------------------------------------------------------------------
# Exp-2: 纯κ + μ监督 (预期最稳定)
# -----------------------------------------------------------------------------
echo ""
echo "[Exp-2] 纯κ + μ监督 - 全数据 (λ_KL=0, λ_κ=5.0, λ_μ=2.0)"
echo "----------------------------------------------"
$BASE_CMD \
    --lambda_kl 0.0 \
    --lambda_kappa 5.0 \
    --lambda_mu 2.0 \
    --exp_name "Exp2_kappa_mu_only"

# =============================================================================
# 第二组: KL配置对比
# =============================================================================

# -----------------------------------------------------------------------------
# Exp-3: 纯Forward KL (对照组)
# -----------------------------------------------------------------------------
echo ""
echo "[Exp-3] 纯Forward KL (λ_KL=1.0, λ_κ=0, λ_μ=0)"
echo "----------------------------------------------"
$BASE_CMD \
    --lambda_kl 1.0 \
    --lambda_kappa 0.0 \
    --lambda_mu 0.0 \
    --exp_name "Exp3_forwardKL"

# -----------------------------------------------------------------------------
# Exp-3b: Forward KL + min_kappa=5 (硬下限防坍塌)
# -----------------------------------------------------------------------------
echo ""
echo "[Exp-3b] Forward KL + min_kappa=5 (λ_KL=1.0, 硬下限防κ坍塌)"
echo "----------------------------------------------"
$BASE_CMD \
    --lambda_kl 1.0 \
    --lambda_kappa 0.0 \
    --lambda_mu 0.0 \
    --min_kappa 5.0 \
    --exp_name "Exp3b_forwardKL_minK5"

# -----------------------------------------------------------------------------
# Exp-4: 纯Reverse KL (测试KL方向)
# -----------------------------------------------------------------------------
echo ""
echo "[Exp-4] 纯Reverse KL (λ_KL=1.0, λ_κ=0, λ_μ=0, reverse)"
echo "----------------------------------------------"
$BASE_CMD \
    --lambda_kl 1.0 \
    --lambda_kappa 0.0 \
    --lambda_mu 0.0 \
    --reverse_kl \
    --exp_name "Exp4_reverseKL"

# -----------------------------------------------------------------------------
# Exp-5: Forward KL + κ监督
# -----------------------------------------------------------------------------
echo ""
echo "[Exp-5] Forward KL + κ监督 (λ_KL=1.0, λ_κ=5.0, λ_μ=0)"
echo "----------------------------------------------"
$BASE_CMD \
    --lambda_kl 1.0 \
    --lambda_kappa 5.0 \
    --lambda_mu 0.0 \
    --exp_name "Exp5_KL_kappa"

# -----------------------------------------------------------------------------
# Exp-6: Forward KL + μ监督
# -----------------------------------------------------------------------------
echo ""
echo "[Exp-6] Forward KL + μ监督 (λ_KL=1.0, λ_κ=0, λ_μ=2.0)"
echo "----------------------------------------------"
$BASE_CMD \
    --lambda_kl 1.0 \
    --lambda_kappa 0.0 \
    --lambda_mu 2.0 \
    --exp_name "Exp6_KL_mu"

# -----------------------------------------------------------------------------
# Exp-7: Forward KL + κ + μ监督
# -----------------------------------------------------------------------------
echo ""
echo "[Exp-7] Forward KL + κ + μ监督 (λ_KL=1.0, λ_κ=5.0, λ_μ=2.0)"
echo "----------------------------------------------"
$BASE_CMD \
    --lambda_kl 1.0 \
    --lambda_kappa 5.0 \
    --lambda_mu 2.0 \
    --exp_name "Exp7_KL_kappa_mu"

# =============================================================================
# 第三组: 高级策略
# =============================================================================

# -----------------------------------------------------------------------------
# Exp-8: 预热式训练 (先监督5epoch→再加KL)
# -----------------------------------------------------------------------------
echo ""
echo "[Exp-8] 预热式训练: Stage1=纯监督(5ep), Stage2=加入KL(10ep)"
echo "----------------------------------------------"
# Stage 1: 纯监督预热 (5 epochs)
$BASE_CMD \
    --epochs 5 \
    --lambda_kl 0.0 \
    --lambda_kappa 5.0 \
    --lambda_mu 2.0 \
    --exp_name "Exp8_warmup_supervised"

# 获取Stage 1的checkpoint路径
STAGE1_CKPT=$(ls -td checkpoints/Exp8_warmup_supervised_*/best.pth 2>/dev/null | head -1)
if [ -z "$STAGE1_CKPT" ]; then
    echo "Warning: Stage 1 checkpoint not found, skipping Stage 2"
else
    # Stage 2: 加入KL (10 epochs, λ_KL=1, λ_κ=3, λ_μ=2)
    $BASE_CMD \
        --epochs 10 \
        --lambda_kl 1.0 \
        --lambda_kappa 3.0 \
        --lambda_mu 2.0 \
        --resume "$STAGE1_CKPT" \
        --exp_name "Exp8_with_KL"
fi

# -----------------------------------------------------------------------------
# Exp-9: Loss权重调度 (μ高→低, KL低→高)
# -----------------------------------------------------------------------------
echo ""
echo "[Exp-9] Loss权重调度 (需要代码支持scheduler)"
echo "----------------------------------------------"
# 这个实验需要在代码中实现loss权重scheduler
# 暂时用固定权重的折中方案
$BASE_CMD \
    --lambda_kl 0.5 \
    --lambda_kappa 5.0 \
    --lambda_mu 3.0 \
    --exp_name "Exp9_balanced_weights"

echo ""
echo "=============================================="
echo "All experiments completed!"
echo "Results saved to: checkpoints/"
echo "WandB project: $WANDB_PROJECT"
echo "=============================================="
